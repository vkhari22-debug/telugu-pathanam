import type { ExternalAudioHandlers, SpeakOptions, SpeechBackend, SpeechCallbacks } from './backend';

export interface CloudConfig {
  endpoint: string;
  voice: string;
}

/** Converts our 0.5–2 pitch slider to the semitone range used by cloud TTS services. */
export function pitchToSemitones(pitch: number): number {
  return Math.max(-20, Math.min(20, Math.round((pitch - 1) * 10 * 10) / 10));
}

export function validateEndpoint(endpoint: string): string | null {
  if (!endpoint.trim()) return 'క్లౌడ్ వాయిస్ సర్వర్ చిరునామా ఇవ్వలేదు.';
  try {
    const url = new URL(endpoint);
    const local = url.hostname === 'localhost' || url.hostname === '127.0.0.1';
    if (url.protocol !== 'https:' && !(local && url.protocol === 'http:')) return 'సర్వర్ చిరునామా https:// తో ప్రారంభం కావాలి.';
    return null;
  } catch {
    return 'సర్వర్ చిరునామా సరైనది కాదు.';
  }
}

const CACHE_LIMIT = 4;

/**
 * Plays speech as real audio through an HTMLAudioElement. The audio is
 * generated by the user's own optional TTS server (see /server), which keeps
 * the cloud API key on the server. Because playback happens in a media
 * element, Chrome on Android creates a media session: Bluetooth buttons,
 * lock-screen controls and audio-focus pauses (e.g. navigation prompts) are
 * delivered to the page as media events.
 */
export class CloudAudioBackend implements SpeechBackend {
  readonly kind = 'cloud' as const;
  readonly usesMediaElement = true;
  readonly reportsInterruptions = true;
  readonly audio: HTMLAudioElement;
  private generation = 0;
  private callbacks: SpeechCallbacks | null = null;
  private external: ExternalAudioHandlers | null = null;
  private ownPause = false;
  private ownPlay = false;
  private cache = new Map<string, Promise<string>>();

  constructor(private readonly getConfig: () => CloudConfig, audio?: HTMLAudioElement) {
    this.audio = audio ?? new Audio();
    this.audio.preload = 'auto';
    this.audio.addEventListener('ended', this.handleEnded);
    this.audio.addEventListener('error', this.handleError);
    this.audio.addEventListener('pause', this.handlePause);
    this.audio.addEventListener('play', this.handlePlay);
  }

  private key(text: string, options: SpeakOptions): string {
    const { voice } = this.getConfig();
    return JSON.stringify([text, voice, options.lang, options.rate, options.pitch]);
  }

  private fetchAudio(text: string, options: SpeakOptions): Promise<string> {
    const key = this.key(text, options);
    const cached = this.cache.get(key);
    if (cached) return cached;
    const { endpoint, voice } = this.getConfig();
    const problem = validateEndpoint(endpoint);
    if (problem) return Promise.reject(new Error(problem));
    const request = fetch(`${endpoint.replace(/\/+$/, '')}/synthesize`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        text,
        languageCode: options.lang,
        voice,
        speakingRate: options.rate,
        pitch: pitchToSemitones(options.pitch),
      }),
    }).then(async (response) => {
      if (!response.ok) {
        const detail = await response.text().catch(() => '');
        throw new Error(`క్లౌడ్ వాయిస్ సర్వర్ లోపం (${response.status}). ${detail.slice(0, 160)}`);
      }
      const blob = await response.blob();
      if (!blob.type.startsWith('audio/')) throw new Error('సర్వర్ ఆడియో పంపలేదు.');
      return URL.createObjectURL(blob);
    });
    request.catch(() => this.cache.delete(key));
    this.cache.set(key, request);
    while (this.cache.size > CACHE_LIMIT) {
      const [oldest, value] = this.cache.entries().next().value as [string, Promise<string>];
      this.cache.delete(oldest);
      value.then((url) => this.revokeUnlessPlaying(url)).catch(() => undefined);
    }
    return request;
  }

  private revokeUnlessPlaying(url: string): void {
    if (this.audio.src !== url) URL.revokeObjectURL(url);
  }

  speak(text: string, options: SpeakOptions, callbacks: SpeechCallbacks, upcoming: string[]): void {
    const generation = ++this.generation;
    this.callbacks = callbacks;
    this.stopElement();
    this.fetchAudio(text, options)
      .then((url) => {
        if (generation !== this.generation) return;
        this.audio.src = url;
        this.ownPlay = true;
        return this.audio.play().then(() => {
          if (generation === this.generation) callbacks.onStart();
        });
      })
      .catch((error: unknown) => {
        if (generation !== this.generation) return;
        this.ownPlay = false;
        const message = error instanceof Error ? error.message : String(error);
        if (error instanceof DOMException && error.name === 'NotAllowedError') {
          callbacks.onError('బ్రౌజర్ ఆడియో ప్రారంభాన్ని అడ్డుకుంది. ప్లే బటన్ మళ్లీ నొక్కండి.');
        } else if (/Failed to fetch|NetworkError|Load failed/i.test(message)) {
          callbacks.onError('ఇంటర్నెట్ లేదా క్లౌడ్ వాయిస్ సర్వర్ అందుబాటులో లేదు.');
        } else {
          callbacks.onError(message);
        }
      });
    for (const next of upcoming.slice(0, 2)) this.fetchAudio(next, options).catch(() => undefined);
  }

  private stopElement(): void {
    if (!this.audio.paused) {
      this.ownPause = true;
      this.audio.pause();
    }
  }

  cancel(): void {
    this.generation++;
    this.callbacks = null;
    this.stopElement();
  }

  pause(): boolean {
    if (!this.callbacks || !this.audio.src || this.audio.paused || this.audio.ended) return false;
    this.ownPause = true;
    this.audio.pause();
    return true;
  }

  resume(): boolean {
    if (!this.callbacks || !this.audio.src || !this.audio.paused || this.audio.ended) return false;
    const generation = this.generation;
    const callbacks = this.callbacks;
    this.ownPlay = true;
    this.audio.play().catch((error: unknown) => {
      if (generation !== this.generation) return;
      this.ownPlay = false;
      callbacks.onError(error instanceof Error ? error.message : String(error));
    });
    return true;
  }

  setExternalHandlers(handlers: ExternalAudioHandlers | null): void {
    this.external = handlers;
  }

  private handleEnded = () => {
    const callbacks = this.callbacks;
    if (!callbacks) return;
    this.callbacks = null;
    callbacks.onEnd();
  };

  private handleError = () => {
    const callbacks = this.callbacks;
    if (!callbacks || !this.audio.src) return;
    this.callbacks = null;
    callbacks.onError('ఆడియో ప్లే చేయడంలో లోపం.');
  };

  private handlePause = () => {
    if (this.ownPause) {
      this.ownPause = false;
      return;
    }
    if (this.audio.ended || !this.callbacks) return;
    // Paused by the operating system/browser (audio focus loss, headset unplugged, …).
    this.external?.onExternalPause();
  };

  private handlePlay = () => {
    if (this.ownPlay) {
      this.ownPlay = false;
      return;
    }
    // Resumed by the operating system/browser after a transient interruption.
    this.external?.onExternalPlay();
  };

  dispose(): void {
    this.cancel();
    this.audio.removeEventListener('ended', this.handleEnded);
    this.audio.removeEventListener('error', this.handleError);
    this.audio.removeEventListener('pause', this.handlePause);
    this.audio.removeEventListener('play', this.handlePlay);
    this.audio.removeAttribute('src');
    for (const value of this.cache.values()) value.then((url) => URL.revokeObjectURL(url)).catch(() => undefined);
    this.cache.clear();
  }
}
